export interface ParsedGlyph {
  char: string;
  top: number;
  width: number;
  height: number;
  /** Zeilen als Bool-Raster [y][x]. */
  pixels: boolean[][];
}

export function parseGlyph([char, top, rows]: GlyphDef): ParsedGlyph {
  const lines = rows.split(' ');
  const width = lines[0]?.length ?? 0;
  for (const line of lines) {
    if (line.length !== width) throw new Error(`Glyphe '${char}': ungleiche Zeilenbreite`);
    if (!/^[#.]+$/.test(line)) throw new Error(`Glyphe '${char}': ungültige Zeichen`);
  }
  if (top + lines.length > FONT_CELL_HEIGHT) throw new Error(`Glyphe '${char}': ragt aus der Zelle`);
  return { char, top, width, height: lines.length, pixels: lines.map((l) => [...l].map((c) => c === '#')) };
}

/** Alle Zeichen, die die Pixel-Schrift darstellen kann (inkl. Leerzeichen). */
export function supportedChars(): Set<string> {
  const set = new Set(GLYPHS.map((g) => g[0]));
  set.add(' ');
  return set;
}
